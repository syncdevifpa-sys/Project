SELECT DATABASE() AS banco,VERSION() AS versao;
SELECT TABLE_NAME,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND (
 (TABLE_NAME='tarefas' AND COLUMN_NAME IN ('id_usuario','id_externo')) OR
 (TABLE_NAME='publico_externo' AND COLUMN_NAME='intencao_cadastro') OR
 (TABLE_NAME='docente_requisitos' AND COLUMN_NAME='tipo_solicitado') OR
 (TABLE_NAME='projetos' AND COLUMN_NAME='visibilidade')) ORDER BY TABLE_NAME,COLUMN_NAME;
SELECT TABLE_NAME,INDEX_NAME,COLUMN_NAME,SEQ_IN_INDEX FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='tarefas' AND INDEX_NAME='idx_tarefas_externo' ORDER BY SEQ_IN_INDEX;
SELECT t.CONSTRAINT_NAME,t.ENFORCED,c.CHECK_CLAUSE FROM information_schema.TABLE_CONSTRAINTS t
JOIN information_schema.CHECK_CONSTRAINTS c ON c.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME=t.CONSTRAINT_NAME
WHERE t.CONSTRAINT_SCHEMA=DATABASE() AND t.TABLE_NAME='tarefas' AND t.CONSTRAINT_NAME='chk_tarefa_titular';
SELECT k.COLUMN_NAME,k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,r.DELETE_RULE FROM information_schema.KEY_COLUMN_USAGE k
JOIN information_schema.REFERENTIAL_CONSTRAINTS r ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
WHERE k.CONSTRAINT_SCHEMA=DATABASE() AND k.TABLE_NAME='tarefas';
SELECT versao,checksum,verificado_em FROM arcadia_schema_migrations ORDER BY versao;
