-- PostgreSQL: esquema consolidado. Aplicar apenas em banco novo vazio.

BEGIN;

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE cursos (
    id_curso integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    nome citext NOT NULL UNIQUE,
    nivel text NOT NULL DEFAULT 'tecnico',
    ativo smallint NOT NULL DEFAULT 1,
    regime_etapas text NULL,
    total_etapas smallint  NULL,
    CHECK (char_length(nome)<=120),
    CHECK (nivel IN ('tecnico','graduacao','pos_graduacao')),
    CHECK (ativo IN (0,1)),
    CHECK (regime_etapas IN ('semestral','anual')),
    CHECK (total_etapas>=0)
);

CREATE TABLE usuarios (
    id_externo_origem integer NULL,
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    nome citext NOT NULL,
    nome_social citext ,
    email citext NOT NULL UNIQUE,
    telefone citext ,
    senha citext NOT NULL,
    tipo_usuario text NOT NULL,
    matricula citext UNIQUE,
    id_curso integer NULL,
    periodo smallint  NULL,
    setor citext ,
    sobre text ,
    foto text ,
    preferencias jsonb ,
    is_admin smallint NOT NULL DEFAULT 0,
    situacao text NOT NULL DEFAULT 'ativo',
    ultimo_acesso timestamp without time zone ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CONSTRAINT uq_usuario_origem_externa UNIQUE (id_externo_origem),
    CHECK (char_length(nome)<=100),
    CHECK (char_length(nome_social)<=100),
    CHECK (char_length(email)<=150),
    CHECK (char_length(telefone)<=20),
    CHECK (char_length(senha)<=255),
    CHECK (tipo_usuario IN ('discente','docente','servidor')),
    CHECK (char_length(matricula)<=30),
    CHECK (periodo>=0),
    CHECK (char_length(setor)<=100),
    CHECK (is_admin IN (0,1)),
    CHECK (situacao IN ('ativo','pendente','bloqueado'))
);

CREATE TABLE publico_externo (
    id_externo integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    nome citext NOT NULL,
    email citext NOT NULL UNIQUE,
    telefone citext ,
    senha citext NOT NULL,
    organizacao citext ,
    situacao text NOT NULL DEFAULT 'ativo',
    ultimo_acesso timestamp without time zone ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    email_lembretes smallint NOT NULL DEFAULT 0,
    consentimento_lembretes_em timestamp without time zone NULL,
    intencao_cadastro text NOT NULL DEFAULT 'externo',
    CHECK (char_length(nome)<=100),
    CHECK (char_length(email)<=150),
    CHECK (char_length(telefone)<=20),
    CHECK (char_length(senha)<=255),
    CHECK (char_length(organizacao)<=120),
    CHECK (situacao IN ('ativo','bloqueado')),
    CHECK (email_lembretes IN (0,1)),
    CHECK (intencao_cadastro IN ('externo','docente','servidor','discente'))
);

CREATE TABLE perfil_compartilhamento (
    id_compartilhamento integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL UNIQUE,
    id_externo integer NULL UNIQUE,
    contato_email citext NOT NULL DEFAULT '',
    contato_handle citext NOT NULL DEFAULT '',
    contato_telefone citext NOT NULL DEFAULT '',
    mostrar_email smallint NOT NULL DEFAULT 0,
    mostrar_handle smallint NOT NULL DEFAULT 0,
    mostrar_telefone smallint NOT NULL DEFAULT 0,
    mostrar_foto smallint NOT NULL DEFAULT 0,
    foto text NULL,
    CHECK (char_length(contato_email)<=150),
    CHECK (char_length(contato_handle)<=100),
    CHECK (char_length(contato_telefone)<=30),
    CHECK (mostrar_email IN (0,1)),
    CHECK (mostrar_handle IN (0,1)),
    CHECK (mostrar_telefone IN (0,1)),
    CHECK (mostrar_foto IN (0,1)),
    CONSTRAINT chk_compartilhamento_conta CHECK ( ( id_usuario IS NULL ) <> ( id_externo IS NULL ) )
);

CREATE TABLE tokens (
    id_token integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    id_externo integer NULL,
    token citext NOT NULL UNIQUE,
    dispositivo citext DEFAULT 'Navegador Web',
    ip citext ,
    ultimo_acesso timestamp without time zone ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expiracao timestamp without time zone NOT NULL,
    CHECK (char_length(token)<=255),
    CHECK (char_length(dispositivo)<=150),
    CHECK (char_length(ip)<=45)
);

CREATE TABLE google_identidades (
    google_sub VARCHAR(255)   NOT NULL PRIMARY KEY,
    id_usuario integer NULL UNIQUE,
    id_externo integer NULL UNIQUE,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (char_length(google_sub)<=255),
    CONSTRAINT chk_google_identidade CHECK ( ( id_usuario IS NOT NULL ) <> ( id_externo IS NOT NULL ) )
);

CREATE TABLE recuperacao_senha (
    id_recuperacao integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    id_externo integer NULL,
    token_hash citext NOT NULL UNIQUE,
    expiracao timestamp without time zone NOT NULL,
    usado_em timestamp without time zone NULL,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (char_length(token_hash)<=64)
);

CREATE TABLE seguranca_limites (
    chave CHAR(64)   PRIMARY KEY,
    janela bigint  NOT NULL,
    tentativas bigint  NOT NULL DEFAULT 0,
    expira_em timestamp without time zone NOT NULL,
    CHECK (char_length(chave)<=64),
    CHECK (janela>=0),
    CHECK (tentativas>=0)
);

CREATE TABLE seguranca_email_lock (
    chave smallint PRIMARY KEY
);

CREATE TABLE email_estado (
    tipo text NOT NULL,
    identidade integer NOT NULL,
    email citext NOT NULL,
    regime text NOT NULL,
    confirmado_em timestamp without time zone NULL,
    CHECK (tipo IN ('users','external')),
    CHECK (char_length(email)<=150),
    CHECK (regime IN ('novo','legado')),
    PRIMARY KEY ( tipo , identidade )
);

CREATE TABLE email_tokens (
    id_token_email bigint GENERATED BY DEFAULT AS IDENTITY   PRIMARY KEY,
    tipo text NOT NULL,
    identidade integer NOT NULL,
    email_destino citext NOT NULL,
    email_anterior citext NOT NULL,
    finalidade text NOT NULL,
    token_hash CHAR(64)   NOT NULL UNIQUE,
    expira_em timestamp without time zone NOT NULL,
    usado_em timestamp without time zone NULL,
    CHECK (id_token_email>=0),
    CHECK (tipo IN ('users','external')),
    CHECK (char_length(email_destino)<=150),
    CHECK (char_length(email_anterior)<=150),
    CHECK (finalidade IN ('cadastro','troca')),
    CHECK (char_length(token_hash)<=64)
);

CREATE TABLE avisos (
    id_aviso integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    tipo_publicacao text NOT NULL DEFAULT 'aviso',
    capa text NULL,
    titulo citext NOT NULL,
    resumo text NOT NULL,
    descricao text ,
    categoria text NOT NULL DEFAULT 'matricula',
    publico_alvo text NOT NULL DEFAULT 'todos',
    situacao text NOT NULL DEFAULT 'publicado',
    urgente smallint NOT NULL DEFAULT 0,
    fixado smallint NOT NULL DEFAULT 0,
    referencia citext ,
    data_prazo date NULL,
    data_evento date NULL,
    vagas bigint  NULL,
    detalhes jsonb NULL,
    data_publicacao timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CHECK (tipo_publicacao IN ('aviso','noticia')),
    CHECK (char_length(titulo)<=150),
    CHECK (categoria IN ('matricula','edital','evento','cancelamento','calendario')),
    CHECK (string_to_array(publico_alvo,',') <@ ARRAY['todos','discente','docente','servidor','externo']::text[]),
    CHECK (situacao IN ('rascunho','publicado','arquivado')),
    CHECK (urgente IN (0,1)),
    CHECK (fixado IN (0,1)),
    CHECK (char_length(referencia)<=50),
    CHECK (vagas>=0)
);

CREATE TABLE avisos_lidos (
    id_aviso integer NOT NULL,
    id_usuario integer NOT NULL,
    lido_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY ( id_aviso , id_usuario )
);

CREATE TABLE tarefas (
    id_tarefa integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    id_externo integer NULL,
    titulo citext NOT NULL,
    categoria citext NOT NULL DEFAULT 'Acadêmico',
    responsavel citext ,
    data_entrega date ,
    prioridade text NOT NULL DEFAULT 'media',
    status text NOT NULL DEFAULT 'aberta',
    observacao text ,
    concluida_em date NULL,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CONSTRAINT chk_tarefa_titular CHECK ( ( id_usuario IS NULL ) <> ( id_externo IS NULL ) ),
    CHECK (char_length(titulo)<=150),
    CHECK (char_length(categoria)<=40),
    CHECK (char_length(responsavel)<=100),
    CHECK (prioridade IN ('baixa','media','alta')),
    CHECK (status IN ('aberta','em_andamento','concluida'))
);

CREATE TABLE documentos (
    id_documento integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NOT NULL,
    id_responsavel integer NULL,
    titulo citext NOT NULL,
    motivo text ,
    descricao text ,
    protocolo citext UNIQUE,
    tipo text NOT NULL DEFAULT 'requerimento',
    status text NOT NULL DEFAULT 'solicitado',
    observacao citext ,
    previsao date NULL,
    data_emissao date NULL,
    arquivo citext ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CHECK (char_length(titulo)<=150),
    CHECK (char_length(protocolo)<=20),
    CHECK (tipo IN ('pdf','requerimento','assinatura')),
    CHECK (status IN ('solicitado','em_analise','pendente','pronto')),
    CHECK (char_length(observacao)<=255),
    CHECK (char_length(arquivo)<=255)
);

CREATE TABLE calendario (
    origem_calendario text NOT NULL DEFAULT 'ifpa',
    id_evento integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    titulo citext NOT NULL,
    descricao text ,
    categoria text NOT NULL DEFAULT 'evento',
    oculto smallint NOT NULL DEFAULT 0,
    visibilidade text NOT NULL DEFAULT 'publico',
    periodo_letivo citext ,
    data_evento date NOT NULL,
    data_fim date NULL,
    hora_inicio time NULL,
    hora_fim time NULL,
    local citext ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CHECK (origem_calendario IN ('agenda','ifpa')),
    CHECK (char_length(titulo)<=150),
    CHECK (categoria IN ('matricula','cancelamento','evento','edital','feriado','ferias','aniversario','atividades_campus','sabado_letivo','periodo_academico','culminancia_bimestral','recesso','registro_academico','ponto_facultativo','avaliacao','interrupcao_presencial','ferias_docentes')),
    CHECK (visibilidade IN ('publico','pessoal','institucional','comunidade')),
    CHECK (char_length(periodo_letivo)<=60),
    CHECK (char_length(local)<=150)
);

CREATE TABLE projetos (
    fixado smallint NOT NULL DEFAULT 0,
    visibilidade text NOT NULL DEFAULT 'privado',
    permite_externos smallint NOT NULL DEFAULT 0,
    id_projeto integer GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    id_usuario integer NULL,
    titulo citext NOT NULL,
    descricao text NOT NULL,
    capa text NULL,
    eixo text NOT NULL DEFAULT 'pesquisa',
    responsavel_nome citext ,
    rotulo_responsavel citext NOT NULL DEFAULT 'Coordenação',
    vagas bigint  NOT NULL DEFAULT 0,
    unidade_vaga citext NOT NULL DEFAULT 'vagas',
    link citext ,
    situacao text NOT NULL DEFAULT 'ativo',
    aprovacao text NOT NULL DEFAULT 'pendente',
    aprovado_por integer NULL,
    data_inicio date ,
    data_fim date ,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CHECK (fixado IN (0,1)),
    CHECK (visibilidade IN ('privado','publico')),
    CHECK (char_length(titulo)<=150),
    CHECK (eixo IN ('pesquisa','extensao','ensino','inovacao')),
    CHECK (char_length(responsavel_nome)<=100),
    CHECK (char_length(rotulo_responsavel)<=20),
    CHECK (vagas>=0),
    CHECK (char_length(unidade_vaga)<=20),
    CHECK (char_length(link)<=500),
    CHECK (situacao IN ('ativo','inscricoes','em_selecao','em_andamento','encerrado')),
    CHECK (aprovacao IN ('pendente','aprovado','recusado'))
);

CREATE TABLE projeto_inscricoes (
    id_projeto integer NOT NULL,
    id_usuario integer NOT NULL,
    status text NOT NULL DEFAULT 'inscrito',
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (status IN ('inscrito','aprovado','recusado','cancelado')),
    PRIMARY KEY ( id_projeto , id_usuario )
);

