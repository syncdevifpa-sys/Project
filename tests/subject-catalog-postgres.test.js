const {test}=require('node:test'),assert=require('node:assert/strict');
test('catálogo consolidado executa no PostgreSQL e reimportar preserva nomes legados sem duplicar', async () => {
 const {PGlite}=require('@electric-sql/pglite');
 const {citext}=require('@electric-sql/pglite/contrib/citext');
 const {prepareAll}=require('../tools/import-belem-subjects.cjs');
 const data=require('../backend/catalog/belem-curriculos-sigaa.json');
 const result=prepareAll(data),db=new PGlite({extensions:{citext}});
 try {
  assert.equal(result.courses,57);
  assert.equal(data.falhas.length,0);
 for(const course of data.cursos){
  const years=course.matrizes.map(m=>Number(m.resumo.match(/Criado em (\d{4})/)[1]));
  assert.equal(new Set(years).size,1);
  if(course.matrizes.length>1)assert.equal(new Set(course.matrizes.map(m=>m.vigencia.ano+'.'+m.vigencia.periodo)).size,1);
 }
  assert.ok(result.count>1000);
  await db.exec('CREATE EXTENSION citext; CREATE TABLE academico_catalogo_disciplinas(id_catalogo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome citext NOT NULL CHECK(char_length(nome)<=150),nome_chave varchar(160) UNIQUE NOT NULL,legado smallint DEFAULT 0,ativo smallint DEFAULT 1)');
  const first=data.cursos.flatMap(c=>c.matrizes.flatMap(m=>m.disciplinas||[]))[0];
  await db.query('INSERT INTO academico_catalogo_disciplinas(nome,nome_chave,legado,ativo) VALUES($1,$2,1,0)',[first.nome,'legado:1']);
  await db.exec(result.postgres);
  assert.equal(Number((await db.query('SELECT count(*) AS total FROM academico_catalogo_disciplinas')).rows[0].total),result.count);
  await db.exec(result.postgres);
  assert.equal(Number((await db.query('SELECT count(*) AS total FROM academico_catalogo_disciplinas')).rows[0].total),result.count);
  const legacy=(await db.query("SELECT * FROM academico_catalogo_disciplinas WHERE nome_chave='legado:1'")).rows[0];
  assert.equal(legacy.ativo,0);assert.equal(legacy.legado,1);assert.equal(legacy.nome,first.nome);
 } finally {await db.close();}
});
